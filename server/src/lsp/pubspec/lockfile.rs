use std::collections::HashMap;
use std::path::Path;

use crate::lsp::pubspec::version::strip_quotes;

/// Parses a `pubspec.lock` file into a map of `package_name -> locked_version`.
#[must_use]
pub fn parse_pubspec_lock(content: &str) -> HashMap<String, String> {
    let mut locked = HashMap::new();
    let mut in_packages = false;
    let mut current_pkg: Option<String> = None;

    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }

        let indent = line.chars().take_while(|&c| c == ' ').count();
        if indent == 0 {
            in_packages = trimmed == "packages:";
            current_pkg = None;
            continue;
        }

        if !in_packages {
            continue;
        }

        if indent == 2 {
            if let Some(pkg) = trimmed.strip_suffix(':') {
                current_pkg = Some(pkg.trim().to_string());
            } else {
                current_pkg = None;
            }
        } else if indent == 4
            && let Some(pkg) = &current_pkg
            && let Some(ver_raw) = trimmed.strip_prefix("version:")
        {
            let version = strip_quotes(ver_raw).trim();
            if !version.is_empty() {
                locked.insert(pkg.clone(), version.to_string());
            }
        }
    }

    locked
}

/// Reads and parses the sibling `pubspec.lock` next to a `pubspec.yaml` file if it exists.
pub async fn load_sibling_lockfile(pubspec_path: &Path) -> HashMap<String, String> {
    let Some(parent) = pubspec_path.parent() else {
        return HashMap::new();
    };
    let lock_path = parent.join("pubspec.lock");
    match tokio::fs::read_to_string(&lock_path).await {
        Ok(content) => parse_pubspec_lock(&content),
        Err(_) => HashMap::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_locked_versions_under_packages_section() {
        let lock = r#"
# Generated by pub
packages:
  dio:
    dependency: "direct main"
    source: hosted
    version: "5.7.0"
  intl:
    dependency: "direct main"
    source: hosted
    version: '0.19.0'
sdks:
  dart: ">=3.5.0 <4.0.0"
"#;
        let map = parse_pubspec_lock(lock);
        assert_eq!(map.get("dio").map(String::as_str), Some("5.7.0"));
        assert_eq!(map.get("intl").map(String::as_str), Some("0.19.0"));
        assert!(!map.contains_key("dart"));
    }
}
